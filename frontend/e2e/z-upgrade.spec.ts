async function login(page: Page, username: string) {
  await page.goto('/login');
  await page.getByLabel('Username').fill(username);
  await page.getByLabel('Password', { exact: true }).fill('LearnTogether42!');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Sign out' })).toBeVisible();
}
async function create(page: Page, resource: string, data: Record<string, unknown>) {
  const result = await page.evaluate(async ({ resource, data }) => {
    const token = decodeURIComponent(document.cookie.split('; ').find(v => v.startsWith('csrftoken='))!.split('=')[1]);
    const response = await fetch(`/api/v1/${resource}/`, { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-CSRFToken': token }, body: JSON.stringify(data) });
    return { status: response.status, data: await response.json() };
  }, { resource, data });
  expect(result.status, JSON.stringify(result.data)).toBe(201);
  return result.data;
}

