import { test, expect } from "@playwright/test";
import { chooseRelation } from "./helpers";

import { login, logout, write, activate } from "./lifecycle-helpers";
import { randomUUID } from "node:crypto";

test("school class, direct teaching, results and reviewed promotion preserve learner history", async ({page}) => {
  test.setTimeout(180000);
  page.setDefaultTimeout(15000);
  const stamp = Date.now();
  const prefix = `school-${stamp}`, adminName = `${prefix}-admin`, teacherName = `${prefix}-teacher`, studentName = `${prefix}-student`;
  await login(page, "superadmin", "LearnTogether42!");
  const school = await write(page, "institutes", {name: `Fresh School ${stamp}`, code: prefix, kind: "school"});
  await write(page, "memberships", {institute: school.id, role: "admin", username: adminName, email: `${adminName}@example.test`});
  await logout(page); await activate(page, adminName);
  await page.goto("/academics");
  await page.getByRole("link", {name: "Manage Classes & Grades", exact: true}).click();
  await expect(page.getByRole("heading", {name: "Classes & Grades"})).toBeVisible();
  await expect(page.getByRole("link", {name: "Teacher appointments", exact: true})).toHaveCount(0);
  expect((await page.request.get("/api/v1/units/")).status()).toBe(403);
  await page.goto("/programs");
  await page.getByRole("button", {name: "Add new"}).click();
  await expect(page.getByRole("dialog").getByLabel("Academic structure")).toHaveCount(0);
  await page.getByRole("dialog").getByRole("textbox", {name: "Name", exact: true}).fill(`Grade A ${stamp}`);
  const created = page.waitForResponse(response => response.url().endsWith("/api/v1/programs/") && response.request().method() === "POST");
  await page.getByRole("button", {name: "Create record", exact: true}).click();
  const saved = await created; expect(saved.status()).toBe(201); const program = await saved.json();
  expect(program.structure).toBe("annual"); expect(program.duration_terms).toBe(1);
  await expect(page.getByRole("dialog")).not.toBeVisible();
  const year = await write(page, "years", {name: `School year ${stamp}`, start: "2026-01-01", end: "2026-12-31"});
  const term = await write(page, "terms", {name: `Annual teaching ${stamp}`, year: year.id, start: year.start, end: year.end, status: "active"});
  expect(term.period_type).toBe("annual");
  const section = await write(page, "sections", {name: "Section A", program: program.id});
  const subject = await write(page, "courses", {name: `School subject ${stamp}`, code: `SC${stamp}`});
  await write(page, "curriculum", {program: program.id, course: subject.id, stage: 1, required: true});
  const teacher = await write(page, "memberships", {role: "teacher", username: teacherName, email: `${teacherName}@example.test`});
  const offering = await write(page, "offerings", {title: `School delivery ${stamp}`, course: subject.id, term: term.id, section: section.id, teachers: [teacher.user], assignment_weight: 0, quiz_weight: 0, manual_weight: 100});
  const admission = await write(page, "admissions", {key: randomUUID(), preview: false, username: studentName, email: `${studentName}@example.test`, first_name: "School", last_name: "Learner", student_identifier: "S001", program: program.id, year: year.id, term: term.id, stage: 1, section: section.id, offerings: [offering.id]});
  const student = await (await page.request.get(`/api/v1/memberships/${admission.membership}/`)).json();
  const identity = await (await page.request.get("/api/v1/auth/me/")).json();
  const institute = await (await page.request.get(`/api/v1/institutes/${identity.institute_id}/`)).json();
  await write(page, `institutes/${institute.id}`, {grading_rules: {...institute.grading_rules, progression_policy: "all_required_pass"}}, "PATCH");
  const nextProgram = await write(page, "programs", {name: `Grade B ${stamp}`});
  const nextYear = await write(page, "years", {name: `Next school year ${stamp}`, start: "2027-01-01", end: "2027-12-31"});
  await logout(page); await activate(page, teacherName);
  await write(page, "manual-grades", {offering: offering.id, student: student.user, title: "Released class result", marks: 90, max_marks: 100, released: true});
  const attendance = await write(page, "attendance-sessions", {offering: offering.id, date: "2026-10-14", title: "Class attendance"});
  await write(page, `attendance-sessions/${attendance.id}/mark`, {records: [{student: student.user, status: "present"}]});
  await logout(page); await login(page, adminName);
  await page.goto(`/student-placement/${student.id}`);
  await page.getByRole("button", {name: "Review academic decision", exact: true}).click();
  const dialog = page.getByRole("dialog");
  await expect(dialog.getByRole("button", {name: "Admission batch (optional)", exact: true})).toHaveCount(0);
  // Seeded school terminology is retained, while structural modules adapt by type.
  const profile = (await (await page.request.get("/api/v1/auth/me/")).json()).institute_profile;
  await chooseRelation(page, profile.terminology.program || "Grade level", nextProgram.name);
  await chooseRelation(page, profile.terminology.year || "Academic year", nextYear.name);
  await dialog.getByLabel("Decision reason").fill("Academic board reviewed the released class results");
  await dialog.getByRole("button", {name: "Preview academic decision"}).click();
  await expect(dialog.getByRole("region", {name: "Academic decision evidence"})).toContainText("90%");
  await dialog.getByLabel("I reviewed the academic evidence and authorize this decision.").check();
  await dialog.getByRole("button", {name: "Confirm academic decision"}).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.getByRole("status")).toContainText("Academic decision saved");
  const placements = await (await page.request.get(`/api/v1/memberships/${student.id}/placements/`)).json();
  expect(placements.results.find((row: {ended_at: string | null}) => !row.ended_at).program).toBe(nextProgram.id);
  await logout(page); await activate(page, studentName);
  await page.getByRole("link", {name: "Academic history", exact: true}).click();
  await expect(page.getByRole("row").filter({hasText: offering.title})).toContainText("90%");
  await expect(page.getByRole("row").filter({hasText: offering.title})).toContainText("Historical");
  expect((await page.request.get(`/api/v1/offerings/${offering.id}/`)).status()).toBe(404);
});
